const uniqueVisaTypes = (visaTypes: string[]): string[] => Array.from(new Set(visaTypes));

export const visaCountryOptions: VisaCountryOption[] = baseVisaCountryOptions.map((destination) => {
  const regionTypes = regionVisaTypeAdditions[destination.region] ?? [];
  const countryTypes = countryVisaTypeAdditions[destination.code] ?? [];

  return {
    ...destination,
    visaTypes: uniqueVisaTypes([...destination.visaTypes, ...regionTypes, ...countryTypes]),
  };
});

export const popularVisaDestinations = visaCountryOptions.filter((destination) => destination.popular);

export const getVisaCountryByCode = (code: string): VisaCountryOption | undefined =>
  visaCountryOptions.find((destination) => destination.code === code);
